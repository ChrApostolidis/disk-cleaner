import { invoke } from "@tauri-apps/api/core";
import { listen } from "@tauri-apps/api/event";
import {
  COMMANDS,
  EVENTS,
  type CleanupDone,
  type CleanupPreview,
  type CleanupProgress,
  type DevDiskApi,
  type HistoryEntry,
  type ReinstallDone,
  type ReinstallOutput,
  type RecycleBinItem,
  type RecycleBinSummary,
  type RestoreResult,
  type Project,
  type FileEntry,
  type ScanError,
  type ScanProgress,
  type ScanSummary,
  type TreemapNode,
  type VolumeInfo,
} from "./types";

export const tauriApi: DevDiskApi = {
  startScan: (root) => invoke<void>(COMMANDS.startScan, { root }),
  cancelScan: () => invoke<void>(COMMANDS.cancelScan),
  getSummary: () => invoke<ScanSummary | null>(COMMANDS.getSummary),
  listProjects: (query) => invoke<Project[]>(COMMANDS.listProjects, { query }),
  listFiles: (query, sort, descending, limit) =>
    invoke<FileEntry[]>(COMMANDS.listFiles, { query, sort, descending, limit }),
  getVolume: () => invoke<VolumeInfo | null>(COMMANDS.getVolume),
  getTreemap: (path, depth) => invoke<TreemapNode>(COMMANDS.getTreemap, { path, depth }),
  previewCleanup: (paths) => invoke<CleanupPreview>(COMMANDS.previewCleanup, { paths }),
  startCleanup: (paths) => invoke<string>(COMMANDS.startCleanup, { paths }),
  listHistory: () => invoke<HistoryEntry[]>(COMMANDS.listHistory),
  restoreEntries: (ids) => invoke<RestoreResult[]>(COMMANDS.restoreEntries, { ids }),
  startReinstall: (projectPath) => invoke<void>(COMMANDS.startReinstall, { projectPath }),
  getRecycleBin: () => invoke<RecycleBinSummary>(COMMANDS.getRecycleBin),
  listRecycleBin: () => invoke<RecycleBinItem[]>(COMMANDS.listRecycleBin),
  emptyRecycleBin: () => invoke<RecycleBinSummary>(COMMANDS.emptyRecycleBin),
  onCleanupProgress: (cb) => listen<CleanupProgress>(EVENTS.cleanupProgress, (e) => cb(e.payload)),
  onCleanupDone: (cb) => listen<CleanupDone>(EVENTS.cleanupDone, (e) => cb(e.payload)),
  onReinstallOutput: (cb) => listen<ReinstallOutput>(EVENTS.reinstallOutput, (e) => cb(e.payload)),
  onReinstallDone: (cb) => listen<ReinstallDone>(EVENTS.reinstallDone, (e) => cb(e.payload)),
  onProgress: (cb) => listen<ScanProgress>(EVENTS.progress, (e) => cb(e.payload)),
  onDone: (cb) => listen<ScanSummary>(EVENTS.done, (e) => cb(e.payload)),
  onError: (cb) => listen<ScanError>(EVENTS.error, (e) => cb(e.payload)),
};
